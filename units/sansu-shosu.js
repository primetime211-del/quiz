// =============================================================
//  算数「小数」 イロハ（3年生）向け
//  §1 小数のしくみ / §2 たし算・ひき算 / §3 小数×整数 / §4 小数÷整数
//  ※ 計算の練習なので電卓はオフ（calc:false）
// =============================================================
(function(){

// 整数 n を 小数 places けた の数として文字にする（最後の0はとる）
const D=(n,p)=>{const s=String(n/Math.pow(10,p));return String(+(+s).toFixed(p));};
const num=(n,p)=>+(n/Math.pow(10,p)).toFixed(p);

registerUnit({
  id:'sansu-shosu',
  subject:'sansu',
  players:['イロハ'],
  calc:false,
  title:'小数',
  desc:'小数のしくみ・たし算ひき算・かけ算わり算',
  levels:[

    {title:'小数のしくみ（テストに出ない）', page:'§1', daily:false, gen:()=>{
      if(Math.random()<.5){const a=ri(1,9),b=ri(0,9),c=ri(1,9);
        return Q(`1が${a}個、0.1が${b}個、0.01が${c}個集まった数を小数で表しなさい。`,'',num(a*100+b*10+c,2),
          '1が4個で4、0.1が5個で0.5、0.01が3個で0.03…のように、位ごとに考えよう',
          [`${a} ＋ ${D(b,1)} ＋ ${D(c,2)} ＝ ${D(a*100+b*10+c,2)}`]);}
      const n=ri(1001,9999);
      return Q(`0.001が${n}個集まった数を小数で表しなさい。`,'',num(n,3),
        '0.001が10個で0.01、100個で0.1、1000個で1',[`0.001が1000個で1なので、${n}個で ${D(n,3)}`]);
    }},

    {title:'小数のたし算', page:'§2', gen:()=>{
      const pa=pick([1,2,2]),pb=pick([1,2]),p=Math.max(pa,pb);
      let a,b;do{a=ri(5,999);b=ri(5,999);}while(a%10===0||b%10===0);
      const A=a*Math.pow(10,p-pa),B=b*Math.pow(10,p-pb),S=A+B;
      return Q(`${D(a,pa)} ＋ ${D(b,pb)} ＝ □`,'',num(S,p),
        '小数点の位置をそろえて、右の位から順に計算しよう。けたが足りないところは0があると考える',
        [tate([D(a,pa),D(b,pb)],'＋',D(S,p))]);
    }},

    {title:'小数のひき算', page:'§2', gen:()=>{
      const k=ri(0,2);let a,pa,b,pb;
      if(k===0){pa=2;pb=2;b=ri(100,800);a=b+ri(20,199);}
      else if(k===1){pa=1;pb=2;b=ri(100,800);a=Math.ceil((b+10)/10)+ri(0,30);}
      else{pa=0;pb=2;a=ri(3,9);b=ri(101,a*100-10);}
      const p=2,A=a*Math.pow(10,p-pa),B=b*Math.pow(10,p-pb),S=A-B;
      return Q(`${D(a,pa)} − ${D(b,pb)} ＝ □`,'',num(S,p),
        k===2?'7は7.00と考えて、小数点をそろえてひこう':'小数点の位置をそろえよう。けたが足りない方には0をつけたす',
        [tate([D(a,pa),D(b,pb)],'−',D(S,p))]);
    }},

    {title:'小数×1けたの整数', page:'§3', gen:()=>{
      const p=pick([1,2,3]),a=ri(p===3?11:12,p===3?999:999),m=ri(2,9);
      return Q(`${D(a,p)} × ${m} ＝ □`,'',num(a*m,p),
        '小数点を考えないで整数と同じように計算し、かけられる数の小数点にそろえて答えに小数点を打とう。さいごの0はとる',
        [`${a} × ${m} ＝ ${a*m}（整数として計算）`,`かけられる数は小数${p}けた → 答えも小数${p}けた`,tate([D(a,p),m],'×',D(a*m,p))]);
    }},

    {title:'小数×2けたの整数', page:'§3', gen:()=>{
      const p=pick([1,2,3]),a=ri(12,p===1?99:999),m=ri(12,48);
      return Q(`${D(a,p)} × ${m} ＝ □`,'',num(a*m,p),
        '整数と同じように筆算して、さいごに小数点を打とう',
        [`${a} × ${m} ＝ ${a*m}（整数として計算）`,`かけられる数は小数${p}けた → ${D(a*m,p)}`]);
    }},

    {title:'小数÷整数（わり切れる）', page:'§4', gen:()=>{
      const d=pick([2,4,5,8,6,3]);let x,q;
      do{x=ri(12,399);}while(d%3===0&&x%3!==0);
      // x は 小数1けたの数（x/10）
      const qs=String(+(x/10/d).toFixed(4));
      return Q(`${D(x,1)} ÷ ${d} ＝ □（わり切れるまで計算しよう）`,'',+qs,
        '商の小数点は、わられる数の小数点にそろえて打つ。わり切れないときは0をつけたして計算を続けよう',
        [`${D(x,1)} ÷ ${d} ＝ ${qs}`,`たしかめ：${qs} × ${d} ＝ ${D(x,1)}`]);
    }},

    {title:'小数÷整数（あまりを出す）', page:'§4', gen:()=>{
      const d=ri(3,9);let x;do{x=ri(60,499);}while(x%d===0);
      if(Math.random()<.5){
        const q=Math.floor(x/10/d),rem=x-q*d*10;
        if(q===0)return GEN_AMARI();
        return P(`${D(x,1)} ÷ ${d} の商を一の位まで求め、あまりも出しなさい。`,[['商',''],['あまり','']],[q,num(rem,1)],
          'あまりの小数点は、わられる数の小数点にそろえて打つよ',
          [`${D(x,1)} ÷ ${d} ＝ ${q} あまり ${D(rem,1)}`,`たしかめ：${d}×${q}＋${D(rem,1)}＝${D(x,1)}`]);
      }
      let qh,rem;do{x=ri(60,499);qh=Math.floor(x*10/d);rem=x*10-qh*d;}while(rem===0);
      return P(`${D(x,1)} ÷ ${d} の商を小数第2位まで求め、あまりも出しなさい。`,[['商',''],['あまり','']],[num(qh,2),num(rem,2)],
        '商を小数第2位（0.01の位）まで出したら止める。あまりの小数点は、わられる数の小数点にそろえる',
        [`${D(x,1)} ÷ ${d} ＝ ${D(qh,2)} あまり ${D(rem,2)}`,`たしかめ：${D(qh,2)}×${d}＋${D(rem,2)}＝${D(x,1)}`]);
    }},

    {title:'ボス：小数の文章題', page:'§2〜4', gen:()=>{
      const k=ri(0,3);
      if(k===0){const a=ri(105,280),b=ri(40,95);
        return Q(`ジュースが${D(a,2)}Lあります。${D(b,2)}L飲みました。残りは何Lですか。`,'L',num(a-b,2),'残りはひき算。小数点をそろえよう',[tate([D(a,2),D(b,2)],'−',D(a-b,2))]);}
      if(k===1){const a=ri(12,95),m=ri(3,9);
        return Q(`1本${D(a,1)}mのリボンが${m}本あります。全部で何mですか。`,'m',num(a*m,1),'1本の長さ × 本数',[`${D(a,1)} × ${m} ＝ ${D(a*m,1)}m`]);}
      if(k===2){const d=pick([2,3,4,5]),q=ri(11,99);
        return Q(`${D(q*d,2)}Lの水を${d}人で同じ量ずつ分けると、1人分は何Lですか。`,'L',num(q,2),'等分するときはわり算。わり切れるまで計算しよう',[`${D(q*d,2)} ÷ ${d} ＝ ${D(q,2)}L`]);}
      const a=ri(150,450),b=ri(80,300),c=ri(50,200);
      return Q(`${D(a,2)}kgの荷物と${D(b,2)}kgの荷物を合わせて、そこから${D(c,2)}kg取り出しました。残りは何kgですか。`,'kg',num(a+b-c,2),'まずたし算、次にひき算',[`${D(a,2)}＋${D(b,2)}＝${D(a+b,2)}`,`${D(a+b,2)}−${D(c,2)}＝${D(a+b-c,2)}kg`]);
    }},
  ]
});

function GEN_AMARI(){const d=ri(3,5),x=d*10*ri(2,4)+ri(1,9);const q=Math.floor(x/10/d),rem=x-q*d*10;
  return P(`${D(x,1)} ÷ ${d} の商を一の位まで求め、あまりも出しなさい。`,[['商',''],['あまり','']],[q,num(rem,1)],
    'あまりの小数点は、わられる数の小数点にそろえて打つよ',[`${D(x,1)} ÷ ${d} ＝ ${q} あまり ${D(rem,1)}`,`たしかめ：${d}×${q}＋${D(rem,1)}＝${D(x,1)}`]);}

})();
