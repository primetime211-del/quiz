// 正しい使い方の文はどれ？（ほかの文は、同じ読みの別の漢字にすりかえてある）
function useQ(list){
  const fill=(x,word)=>plain(x[0]).replace(/【.+?】/,word);
  const item=pick(list),ok=fill(item,item[1]);
  const wrong=uniq(shuffle(list.filter(x=>x[1]!==item[1])).map(x=>fill(x,x[2][0]))).filter(w=>w!==ok&&!list.some(y=>fill(y,y[1])===w)).slice(0,3);
  return C('漢字の使い方が正しい文はどれ？',ok,wrong,'一つずつ、【 】の言葉の意味を考えよう',[`正しい：${ok}`,...wrong.map(w=>`×：${w}`)]);
}
