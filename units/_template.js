// =============================================================
//  新しい単元のひな形（このファイル自体は読みこまれません）
//
//  使い方
//   1. このファイルをコピーして名前を変える（例：units/shakai-todofuken.js）
//   2. id / subject / title / levels を書きかえる
//   3. index.html の「単元ファイル」の所に1行足す
//        <script src="units/shakai-todofuken.js"></script>
//
//  subject は次のどれか： kokugo（国語） sansu（算数） rika（理科） shakai（社会）
//  レベルの数は自由（5でも12でもOK）。地図は自動でその数になります。
//
//  問題の形（gen は呼ばれるたびに1問つくって返す）
//   Q(問題文, 単位, 答え, ヒント, [解説...])          数字を1つ答える
//   P(問題文, [単位1,単位2], [答え1,答え2], ヒント, [解説...])  数字を2つ答える
//   C(問題文, 正解, [まちがい1, まちがい2, ...], ヒント, [解説...])  えらぶ（順番は毎回シャッフル）
//
//  毎回ちがう問題にするには、pick([...]) でリストから選んだり、ri(1,9) で数をつくったりします。
// =============================================================
(function(){

// 問題リストからえらぶタイプの例
const KEN=[
  ['北海道','札幌市'],['宮城県','仙台市'],['愛知県','名古屋市'],['兵庫県','神戸市'],
  ['石川県','金沢市'],['香川県','高松市'],['愛媛県','松山市'],['沖縄県','那覇市'],
];

registerUnit({
  id:'shakai-sample',          // ほかと重ならない名前（英数字とハイフン）
  subject:'shakai',
  title:'都道府県と県庁所在地',
  desc:'サンプル単元',
  levels:[
    {title:'県庁所在地を答える', page:'テキストp.10', gen:()=>{
      const [k,c]=pick(KEN);
      const others=KEN.filter(x=>x[1]!==c).map(x=>x[1]);
      return C(`${k}の県庁所在地はどこ？`, c, shuffle(others).slice(0,3),
        '地図帳で場所を思い出してみよう', [`${k}の県庁所在地は${c}です。`]);
    }},
    {title:'計算の例', gen:()=>{
      const a=ri(2,9),b=ri(2,9);
      return Q(`${a} × ${b} ＝ □`, '', a*b, 'かけ算九九を思い出そう', [`${a} × ${b} ＝ ${a*b}`]);
    }},
  ]
});

})();
