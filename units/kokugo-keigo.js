(function(){

const fromList=list=>{const [q,a,w,h,e]=pick(list);return C(q,a,w,h,[e]);};
// [ふつうの言い方, 尊敬語, 謙譲語]
const VERB=[
  ['行く','いらっしゃる','うかがう・参る'],
  ['来る','いらっしゃる・お見えになる','参る'],
  ['いる','いらっしゃる','おる'],
  ['言う','おっしゃる','申す・申し上げる'],
  ['する','なさる','いたす'],
  ['見る','ご覧になる','拝見する'],
  ['食べる','めしあがる','いただく'],
  ['飲む','めしあがる','いただく'],
  ['聞く','お聞きになる','うかがう・拝聴する'],
  ['知っている','ご存じだ','存じている・存じ上げている'],
  ['会う','お会いになる','お目にかかる'],
  ['あげる（与える）','くださる（くれる）','さしあげる'],
  ['もらう','お受け取りになる','いただく・ちょうだいする'],
  ['思う','お思いになる','存じる'],
  ['着る','お召しになる','着させていただく'],
  ['寝る','お休みになる','休ませていただく'],
  ['見せる','お見せになる','お目にかける・ご覧に入れる'],
];
const one=s=>s.split('・')[0];
// [文, 種類]
const SORT=[
  ['先生が教室にいらっしゃる。','尊敬語'],['校長先生がお話しになる。','尊敬語'],['お客様がめしあがる。','尊敬語'],
  ['先生がご覧になる。','尊敬語'],['社長がおっしゃる。','尊敬語'],['先生が本を読まれる。','尊敬語'],
  ['わたしが先生のお宅にうかがう。','謙譲語'],['わたしが作品を拝見する。','謙譲語'],['母が申しております。','謙譲語'],
  ['わたしがお荷物をお持ちする。','謙譲語'],['わたしがお菓子をいただく。','謙譲語'],['先生に手紙をさしあげる。','謙譲語'],
  ['明日は雨です。','丁寧語'],['わたしは学校へ行きます。','丁寧語'],['ここが図書館でございます。','丁寧語'],
  ['これはわたしのかばんです。','丁寧語'],['毎朝七時に起きます。','丁寧語'],
];
// 「お（ご）〜になる」＝尊敬、「お（ご）〜する」＝謙譲 にする動詞
const OV=[['待つ','お待ちになる','お待ちする'],['書く','お書きになる','お書きする'],['持つ','お持ちになる','お持ちする'],['帰る','お帰りになる','お帰りする'],['説明する','ご説明になる','ご説明する'],['案内する','ご案内になる','ご案内する'],['届ける','お届けになる','お届けする'],['送る','お送りになる','お送りする']];

registerUnit({
  id:'kokugo-keigo',
  subject:'kokugo',
  players:['カンナ'],
  title:'敬語',
  desc:'尊敬語・謙譲語・丁寧語',
  levels:[

    {title:'敬語の3つの種類',gen:()=>fromList([
      ['相手や話題の人の動作をうやまって、その人を高める敬語は？','尊敬語',['謙譲語','丁寧語','美化語'],'動作をするのは「目上の人」','尊敬語：相手（目上の人）の動作を高める。例：いらっしゃる、おっしゃる'],
      ['自分や身内の動作をへりくだって、相手を高める敬語は？','謙譲語',['尊敬語','丁寧語','美化語'],'動作をするのは「自分」','謙譲語：自分の動作を低くして、相手を高める。例：うかがう、申す'],
      ['「です」「ます」「ございます」を使って、ていねいに言う敬語は？','丁寧語',['尊敬語','謙譲語','方言'],'聞き手へのていねいさ','丁寧語：です・ます・ございます'],
      ['尊敬語を使うのは、だれの動作について話すとき？','目上の人や相手の動作',['自分の動作','自分の家族の動作','物の名前'],'うやまう相手','尊敬語は、目上の人や相手の動作に使う'],
      ['謙譲語を使うのは、だれの動作について話すとき？','自分や自分の身内の動作',['先生の動作','お客様の動作','相手の動作'],'へりくだる','謙譲語は、自分や身内（家族）の動作に使う'],
      ['「お茶」「ご飯」のように、言葉に「お」「ご」をつけて上品にする言い方を何という？','美化語',['尊敬語','謙譲語','外来語'],'丁寧語のなかま','美化語：お茶・お水・ご飯など。丁寧語のなかまとすることもある'],
    ])},

    {title:'種類を見分ける',gen:()=>{
      const [s,t]=pick(SORT);
      return C(`次の文の敬語の種類はどれ？<br><b>${s}</b>`,t,['尊敬語','謙譲語','丁寧語'].filter(x=>x!==t),'動作をしているのはだれ？ 目上の人なら尊敬語、自分なら謙譲語、「です・ます」だけなら丁寧語',[`${s} → ${t}`]);
    }},

    {title:'尊敬語（特別な言葉）',gen:()=>{
      const [v,son,ken]=pick(VERB);
      if(Math.random()<.5){const w=[...new Set(shuffle(VERB.filter(x=>x[0]!==v).map(x=>one(x[1]))).filter(x=>!son.split('・').includes(x)&&x!==one(ken)))];
        return C(`「${v}」の尊敬語はどれ？`,one(son),[one(ken),...w.slice(0,2)],'相手（目上の人）の動作を高める言い方',[`${v}：尊敬語「${son}」／謙譲語「${ken}」`]);}
      return C(`「${one(son)}」は、何という言葉の尊敬語？`,v,shuffle(VERB.filter(x=>x[1]!==son&&!x[1].split('・').includes(one(son))).map(x=>x[0])).slice(0,3),'もとの動作を考えよう',[`${one(son)}＝「${v}」の尊敬語`]);
    }},

    {title:'謙譲語（特別な言葉）',gen:()=>{
      const [v,son,ken]=pick(VERB);
      if(Math.random()<.5){const w=[...new Set(shuffle(VERB.filter(x=>x[0]!==v).map(x=>one(x[2]))).filter(x=>!ken.split('・').includes(x)&&x!==one(son)))];
        return C(`「${v}」の謙譲語はどれ？`,one(ken),[one(son),...w.slice(0,2)],'自分の動作をへりくだる言い方',[`${v}：謙譲語「${ken}」／尊敬語「${son}」`]);}
      return C(`「${one(ken)}」は、何という言葉の謙譲語？`,v,shuffle(VERB.filter(x=>x[0]!==v&&!x[2].split('・').includes(one(ken))).map(x=>x[0])).slice(0,3),'もとの動作を考えよう',[`${one(ken)}＝「${v}」の謙譲語（${ken}）`]);
    }},

    {title:'お〜になる・お〜する',gen:()=>{
      const [v,son,ken]=pick(OV),k=ri(0,2);
      if(k===0)return C(`先生が「${v}」ことを敬語で言うとき、正しいのはどれ？`,son,[ken,`${v}ます`],'先生の動作 → 尊敬語「お（ご）〜になる」',[`尊敬語：${son}／謙譲語：${ken}`]);
      if(k===1)return C(`わたしが先生のために「${v}」ことを敬語で言うとき、正しいのはどれ？`,ken,[son,`${v}れる`],'自分の動作 → 謙譲語「お（ご）〜する」',[`謙譲語：${ken}／尊敬語：${son}`]);
      return fromList([
        ['「先生が本を読まれる」の「れる」は、どの意味？','尊敬',['受け身','可能','自発'],'先生の動作をうやまっている','「れる・られる」は尊敬の意味でも使う'],
        ['「お〜になる」は、どの種類の敬語の形？','尊敬語',['謙譲語','丁寧語','美化語'],'お待ちになる','お（ご）〜になる＝尊敬語'],
        ['「お〜する」は、どの種類の敬語の形？','謙譲語',['尊敬語','丁寧語','美化語'],'お持ちする','お（ご）〜する＝謙譲語'],
        ['「〜させていただく」は、どの種類の敬語？','謙譲語',['尊敬語','丁寧語','美化語'],'自分の動作','させていただく＝謙譲語'],
      ]);
    }},

    {title:'正しい敬語・まちがった敬語',gen:()=>fromList([
      ['先生に「どうぞ」とすすめるとき、正しいのはどれ？','どうぞ、めしあがってください。',['どうぞ、いただいてください。','どうぞ、お食べしてください。','どうぞ、食べてください。'],'先生の動作には尊敬語','「いただく」は謙譲語なので、相手の動作には使わない'],
      ['お客様に聞くとき、正しいのはどれ？','何をご覧になりますか。',['何を拝見しますか。','何をお見えしますか。','何を見られますか。'],'お客様の動作には尊敬語','拝見するは謙譲語。「ご覧になる」が尊敬語'],
      ['ほかの会社の人に、自分の会社の社長のことを言うとき、正しいのはどれ？','社長の田中は、ただいま外出しております。',['田中社長は、ただいま外出していらっしゃいます。','社長の田中さんは、外出なさっています。','田中社長様は、外出されています。'],'身内（自分の側）のことは謙譲語','外の人に話すときは、自分の会社の人にも尊敬語を使わない'],
      ['先生に電話で「母がそう言っていました」と伝えるとき、正しいのはどれ？','母がそう申しておりました。',['お母さんがそうおっしゃっていました。','母がそうおっしゃっていました。','お母様がそう言われていました。'],'家族は身内','身内の動作には謙譲語「申す」を使う'],
      ['先生に「わたしが行きます」と言うとき、正しいのはどれ？','わたしがうかがいます。',['わたしがいらっしゃいます。','わたしがお行きになります。','わたしが行かれます。'],'自分の動作には謙譲語','自分の動作に尊敬語「いらっしゃる」は使わない'],
      ['まちがった敬語はどれ？','先生が申されました。',['先生がおっしゃいました。','わたしが申し上げました。','父が申しておりました。'],'「申す」は謙譲語','先生の動作に謙譲語「申す」を使うのはまちがい。「おっしゃる」が正しい'],
      ['まちがった敬語はどれ？','先生が拝見されました。',['先生がご覧になりました。','わたしが拝見しました。','わたしがお見せしました。'],'「拝見する」は謙譲語','先生の動作には「ご覧になる」'],
      ['まちがった敬語はどれ？','お客様がお帰りしました。',['お客様がお帰りになりました。','わたしがお送りしました。','お客様が帰られました。'],'お〜する は謙譲語','お客様の動作には「お帰りになる」'],
      ['「おっしゃられる」が正しくないのはなぜ？','尊敬語を二重に使っている（二重敬語）から',['謙譲語だから','丁寧語がないから','方言だから'],'おっしゃる＋れる','「おっしゃる」だけで尊敬語。「れる」まで重ねると二重敬語'],
    ])},

    {title:'言いかえ問題',gen:()=>{
      const T=[
        ['先生が、明日学校に<u>来る</u>。','いらっしゃる','参る','先生の動作'],
        ['先生の作品を<u>見る</u>。（わたしが）','拝見する','ご覧になる','自分の動作'],
        ['校長先生が、朝礼で<u>言う</u>。','おっしゃる','申し上げる','校長先生の動作'],
        ['わたしは、先生のお宅に<u>行く</u>。','うかがう','いらっしゃる','自分の動作'],
        ['お客様が、ケーキを<u>食べる</u>。','めしあがる','いただく','お客様の動作'],
        ['わたしは、先生からお手紙を<u>もらう</u>。','いただく','お受け取りになる','自分の動作'],
        ['先生は、そのことを<u>知っている</u>。','ご存じだ','存じている','先生の動作'],
        ['わたしが、先生に花を<u>あげる</u>。','さしあげる','くださる','自分の動作'],
        ['先生が、わたしに本を<u>くれる</u>。','くださる','さしあげる','先生の動作'],
        ['わたしが、先生に<u>会う</u>。','お目にかかる','お会いになる','自分の動作'],
        ['先生が、あとで<u>する</u>。','なさる','いたす','先生の動作'],
        ['わたしが、そうじを<u>する</u>。','いたす','なさる','自分の動作'],
      ];
      const [s,a,w,h]=pick(T);
      return C(`次の文の線の言葉を、正しい敬語に直したものはどれ？<br><b>${s}</b>`,a,[w,shuffle(VERB.map(x=>one(x[1])).concat(VERB.map(x=>one(x[2])))).find(x=>x!==a&&x!==w)],`${h} → ${h.startsWith('自分')?'謙譲語':'尊敬語'}`,[`${s.replace(/<[^>]+>/g,'')} → ${a}（${h.startsWith('自分')?'謙譲語':'尊敬語'}）`]);
    }},

    {title:'ボス：敬語ミックス',gen:()=>{const u=UNITS.find(x=>x.id==='kokugo-keigo');return pick(u.levels.slice(1,-1)).gen();}},
  ]
});

})();
