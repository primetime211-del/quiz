const fromList=list=>{const [q,a,w,h,e]=pick(list);return C(q,a,w,h,[e]);};
function termQ(list,hint){
  const [t,d]=pick(list),w=shuffle(list.filter(x=>x[0]!==t)).slice(0,3).map(x=>x[0]);
  return C(`${d}。これは何ですか（だれですか）。`,t,w,hint,[`${t}：${d}`]);
}
function yearQ(list){const [ev,y,h]=pick(list);return Q(`「${ev}」は何年ですか。`,'年',y,h||`${Math.floor(y/100)+1}世紀のできごと`,[`${y}年：${ev}`]);}
function orderQ(list){
  let ev;do{ev=shuffle(list).slice(0,3);}while(new Set(ev.map(e=>e[1])).size<3);
  const ok=ev.slice().sort((a,b)=>a[1]-b[1]),s=a=>a.map(e=>e[0]).join(' → ');
  const perms=[[0,2,1],[1,0,2],[1,2,0],[2,0,1],[2,1,0]].map(p=>p.map(i=>ok[i]));
  return C('次のできごとを古い順に並べたものはどれ？',s(ok),shuffle(perms).slice(0,3).map(s),'それぞれ何年ごろのできごとか思い出そう',ok.map(e=>`${e[1]}年　${e[0]}`));
}
// 人物と政策の組み合わせ：[人物, [やったこと...]]
function whoDid(list,hint){
  const [p,acts]=pick(list),a=pick(acts);
  return C(`「${a}」をおこなった人物はだれ？`,p,shuffle(list.filter(x=>x[0]!==p).map(x=>x[0])).slice(0,3),hint,[`${a} … ${p}`]);
}
function didWhat(list,hint){
  const [p,acts]=pick(list),a=pick(acts);
  const wrong=shuffle(list.filter(x=>x[0]!==p).flatMap(x=>x[1])).slice(0,3);
  return C(`${p}がおこなったことはどれ？`,a,wrong,hint,[`${p}：${acts.join('、')}`]);
}

