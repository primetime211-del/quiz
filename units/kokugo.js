const okFor=max=>s=>grade(s)<=max;
const mark=s=>s.replace(/【(.+?)】/,'<u><b>$1</b></u>');
// 文と答えは学年内、まちがいの選択肢は学年をこえるものを外す（2つ以上残るものだけ使う）
function pool(list,max,textIdx,ansIdx){
  return list.map(x=>{
    if(max>=7)return x;
    if(!okFor(max)(x[textIdx])||!okFor(max)(x[ansIdx]))return null;
    const w=x[2].filter(okFor(max));return w.length>=2?[x[0],x[1],w,...x.slice(3)]:null;
  }).filter(Boolean);
}
function yomiQ(list,hint){const [s,a,w]=pick(list);return C(`次の文の、太字の言葉の読み方はどれ？<br>${mark(s)}`,a,w.slice(0,3),hint,[`${s.replace(/[【】]/g,'')} → ${a}`]);}
function kakiQ(list,hint){const [s,a,w]=pick(list);return C(`次の文の、太字のカタカナを漢字にしたものはどれ？<br>${mark(s)}`,a,w.slice(0,3),hint,[`${s.replace(/【.+?】/,a)}`]);}
function pairQ(list,kind,sym,hint){const [x,a,w]=pick(list);return C(`「${x}」の${kind}はどれ？`,a,w.slice(0,3),hint,[`${x} ${sym} ${a}`]);}
function meanQ(list,hint){
  const it=pick(list),[w,m]=it,wrong=shuffle([...new Set(list.filter(x=>x[1]!==m).map(x=>x[1]))]).slice(0,3);
  if(Math.random()<.5)return C(`「${w}」の意味はどれ？`,m,wrong,hint,[`${w}：${m}`]);
  const wn=shuffle(list.filter(x=>x[1]!==m).map(x=>x[0])).slice(0,3);
  return C(`「${m}」という意味のものはどれ？`,w,wn,hint,[`${w}：${m}`]);
}
function relQ(pairs,all,kind,same){
  const [a,b]=shuffle(pick(pairs)),bad=new Set(pairs.flat());
  const wrong=shuffle(all.map(x=>x[0]).filter(x=>!bad.has(x))).slice(0,3);
  return C(`「${a}」と${kind}のことわざはどれ？`,b,wrong,same?'意味を思いうかべて、同じことを言っているものをさがそう':'意味が正反対になるものをさがそう',[`${a} ／ ${b}`]);
}
