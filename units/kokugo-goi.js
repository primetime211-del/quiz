function meanQ(list,hint){
  const [w,m]=pick(list);const ex=list.filter(x=>near(w).includes(x[0])).map(x=>x[1]);
  return C(`「${w}」の意味はどれ？`,m,others(list.map(x=>x[1]),m,3,ex),hint,[`${w}：${m}`]);
}
function wordQ(list,hint){
  const [w,m]=pick(list);
  return C(`「${m}」という意味の言葉はどれ？`,w,others(list.map(x=>x[0]),w,3,near(w)),hint,[`${w}：${m}`]);
}
function bunQ(list,hint){
  const [w,m,s,wr]=pick(list);
  return C(`（　）に入るいちばんよい言葉はどれ？　${s}`,w,wr.slice(0,3),hint,[s.replace('（　）',w),`${w}：${m}`]);
}
