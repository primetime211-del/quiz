const fromList=list=>{const [q,a,w,h,e]=pick(list);return C(q,a,w,h,[e]);};
// [言葉, 説明] から「説明→言葉」の問題
function termQ(list,hint){
  const [t,d]=pick(list),w=shuffle(list.filter(x=>x[0]!==t)).slice(0,3).map(x=>x[0]);
  return C(`${d}。これは何ですか（だれですか）。`,t,w,hint,[`${t}：${d}`]);
}
// 年号：[できごと, 年, ヒント]
function yearQ(list){
  const [ev,y,h]=pick(list);
  return Q(`「${ev}」は何年ですか。`,'年',y,h||`${Math.floor(y/100)+1}世紀のできごと`,[`${y}年：${ev}`]);
}
// 順番：[できごと, 年] から3つ選んで、古い順の並びを答える
function orderQ(list){
  const ev=shuffle(list).slice(0,3);
  if(new Set(ev.map(e=>e[1])).size<3)return orderQ(list);
  const ok=ev.slice().sort((a,b)=>a[1]-b[1]);
  const s=a=>a.map(e=>e[0]).join(' → ');
  const perms=[[0,2,1],[1,0,2],[1,2,0],[2,0,1],[2,1,0]].map(p=>p.map(i=>ok[i]));
  return C('次のできごとを古い順に並べたものはどれ？',s(ok),shuffle(perms).slice(0,3).map(s),
    'それぞれ何年ごろのできごとか思い出そう',ok.map(e=>`${e[1]}年　${e[0]}`));
}

