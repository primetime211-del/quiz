// [言葉, 説明] のリストから「説明→言葉」「言葉→説明」の問題をつくる
function termQ(list,hint,dir){
  const [t,d]=pick(list),others=list.filter(x=>x[0]!==t);
  const wrong=shuffle(others).slice(0,3);
  if((dir||pick(['t','d']))==='t')
    return C(`「${d}」を何といいますか。`,t,wrong.map(x=>x[0]),hint,[`${t}：${d}`]);
  return C(`「${t}」の説明として正しいのはどれ？`,d,wrong.map(x=>x[1]),hint,[`${t}：${d}`]);
}

