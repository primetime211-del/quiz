// 柱状図（かんたんな図）
function column(depths,mark){
  const H=170,top=18,scale=(H-top-10)/50;let s=`<svg viewBox="0 0 220 ${H+10}" style="width:100%;max-width:240px;display:block;margin:6px auto">`;
  for(let m=0;m<=50;m+=10)s+=`<text x="40" y="${top+m*scale+4}" text-anchor="end" font-size="11" fill="currentColor">${m}m</text><line x1="44" y1="${top+m*scale}" x2="160" y2="${top+m*scale}" stroke="currentColor" stroke-opacity=".25" stroke-dasharray="3 3"/>`;
  s+=`<rect x="70" y="${top}" width="50" height="${50*scale}" fill="none" stroke="currentColor" stroke-width="2"/>`;
  if(mark!=null)s+=`<rect x="70" y="${top+mark*scale-4}" width="50" height="8" fill="#E8B04A"/><text x="128" y="${top+mark*scale+4}" font-size="11" fill="currentColor">凝灰岩</text>`;
  return s+'</svg>';
}

